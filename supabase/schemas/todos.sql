-- Declarative schema: this file is the source of truth for the `todos` table.
-- Edit it, then generate a migration with `pnpm schema:sync -f <migration-name>`.
-- Never declare DML (insert/update/delete) here: schema diffs only track DDL.

create table public.todos (
  id bigint generated by default as identity primary key,
  title text not null,
  is_complete boolean not null default false,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.todos enable row level security;

-- `to authenticated` keeps anonymous requests out (the Supabase Data API connects as
-- the `anon` role when there is no session). `(select auth.uid())` is an initplan, so
-- the call is evaluated once per query instead of once per row.
create policy "Users can read their own todos"
  on public.todos for select to authenticated
  using ((select auth.uid()) = user_id);

create policy "Users can insert their own todos"
  on public.todos for insert to authenticated
  with check ((select auth.uid()) = user_id);

create policy "Users can update their own todos"
  on public.todos for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

create policy "Users can delete their own todos"
  on public.todos for delete to authenticated
  using ((select auth.uid()) = user_id);

-- Explicit Data API grants so `db push` works even if `api.auto_expose_new_tables` is disabled.
-- No `anon` grant: an anonymous key must not reach this table at all.
grant select, insert, update, delete on table public.todos to authenticated;
